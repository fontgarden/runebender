    /// The feature text without the named features, each written as `feature tag {` to
    /// `} tag;` on their own lines, as in the fixture.
    fn without_features(feature_text: &str, tags: &[&str]) -> String {
        let mut out = String::new();
        let mut skipping: Option<String> = None;
        for line in feature_text.lines() {
            if let Some(tag) = &skipping {
                if line.trim() == format!("}} {tag};") {
                    skipping = None;
                }
                continue;
            }
            if let Some(tag) = tags
                .iter()
                .find(|tag| line.trim() == format!("feature {tag} {{"))
            {
                skipping = Some((*tag).to_owned());
                continue;
            }
            out.push_str(line);
            out.push('\n');
        }
        out
    }

