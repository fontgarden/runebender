/// The first line of the generated block.
/// A line that starts with this text starts the block, so a later wording still matches.
pub const BLOCK_BEGIN: &str = "# Begin Arabic features generated by Runebender. \
                               Generate again to replace this block; edits inside it are lost.";

/// The last line of the generated block.
pub const BLOCK_END: &str = "# End Arabic features generated by Runebender.";

/// The part of [`BLOCK_BEGIN`] that identifies the line.
const BEGIN_PREFIX: &str = "# Begin Arabic features generated by Runebender.";

/// The positional features and the glyph name suffix of each, in the order of the shaper.
const FORMS: [(&str, &str); 4] = [
    ("isol", ".isol"),
    ("fina", ".fina"),
    ("medi", ".medi"),
    ("init", ".init"),
];

/// The order of the features in the block, which is the order of the Arabic shaper.
const FEATURE_ORDER: [&str; 6] = ["ccmp", "isol", "fina", "medi", "init", "rlig"];

/// The ranges of the Arabic script, for glyph names of the form `uni0628` and `u10EC5`.
const ARABIC_RANGES: [(u32, u32); 8] = [
    (0x0600, 0x06FF),
    (0x0750, 0x077F),
    (0x0870, 0x089F),
    (0x08A0, 0x08FF),
    (0xFB50, 0xFDFF),
    (0xFE70, 0xFEFF),
    (0x10EC0, 0x10EFF),
    (0x1EE00, 0x1EEFF),
];

/// One generated feature: one lookup of substitution rules.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct GeneratedFeature {
    /// The feature tag, such as `init`.
    pub tag: String,
    /// Whether the lookup skips marks, as a ligature lookup must.
    pub ignore_marks: bool,
    /// The rules, each a complete statement such as `sub beh-ar by beh-ar.init;`.
    pub rules: Vec<String>,
}

/// The generated Arabic features, ready to place in the feature text.
#[derive(Debug, Clone, PartialEq, Eq, Default)]
pub struct GeneratedBlock {
    /// The generated features, in the order of the Arabic shaper.
    pub features: Vec<GeneratedFeature>,
    /// Features that had rules to write but that the feature text defines outside the block.
    /// They are not written.
    pub kept: Vec<String>,
    /// Findings for the designer, such as a ligature whose components are not in the font.
    pub notes: Vec<String>,
    /// The non-default languages of `script arab`, or `None` when the feature text declares no
    /// Arabic language system.
    languages: Option<Vec<String>>,
}

impl GeneratedBlock {
    /// True when no feature has rules.
    pub fn is_empty(&self) -> bool {
        self.features.is_empty()
    }

    /// The number of rules in all features.
    pub fn rule_count(&self) -> usize {
        self.features
            .iter()
            .map(|feature| feature.rules.len())
            .sum()
    }

    /// The generated feature with this tag.
    pub fn feature(&self, tag: &str) -> Option<&GeneratedFeature> {
        self.features.iter().find(|feature| feature.tag == tag)
    }

    /// Add the features, kept features and notes of another block generated from the same
    /// feature text.
    pub fn merge(&mut self, other: Self) {
        self.features.extend(other.features);
        self.features
            .sort_by_key(|feature| feature_rank(&feature.tag));
        for tag in other.kept {
            if !self.kept.contains(&tag) {
                self.kept.push(tag);
            }
        }
        self.kept.sort_by_key(|tag| feature_rank(tag));
        self.notes.extend(other.notes);
        if self.languages.is_none() {
            self.languages = other.languages;
        }
    }

    /// One line for a status bar: the features and their rule counts, and the kept features.
    pub fn summary(&self) -> String {
        let mut text = if self.is_empty() {
            "No Arabic features to generate from glyph names".to_owned()
        } else {
            let parts: Vec<String> = self
                .features
                .iter()
                .map(|feature| format!("{} {}", feature.tag, feature.rules.len()))
                .collect();
            format!("Generated {}", parts.join(", "))
        };
        if !self.kept.is_empty() {
            let _ = write!(text, "; kept own {}", self.kept.join(", "));
        }
        if !self.notes.is_empty() {
            let _ = write!(text, "; {} note(s)", self.notes.len());
        }
        text
    }

    /// The block: [`BLOCK_BEGIN`], the features, and [`BLOCK_END`], each line ending in a
    /// newline.
    /// Empty when there is nothing to generate.
    pub fn text(&self) -> String {
        if self.is_empty() {
            return String::new();
        }
        let mut out = String::new();
        out.push_str(BLOCK_BEGIN);
        out.push('\n');
        out.push_str(
            "# Positional forms and ligatures come from the glyph names, and decompositions \
             from the skeleton table.\n",
        );
        for feature in &self.features {
            let tag = &feature.tag;
            out.push('\n');
            let _ = writeln!(out, "feature {tag} {{");
            if self.languages.is_some() {
                out.push_str("    script arab;\n");
            }
            let _ = writeln!(out, "    lookup generated_{tag} {{");
            if feature.ignore_marks {
                out.push_str("        lookupflag IgnoreMarks;\n");
            }
            for rule in &feature.rules {
                let _ = writeln!(out, "        {rule}");
            }
            let _ = writeln!(out, "    }} generated_{tag};");
            for language in self.languages.iter().flatten() {
                let _ = writeln!(out, "    language {language};");
            }
            let _ = writeln!(out, "}} {tag};");
        }
        out.push('\n');
        out.push_str(BLOCK_END);
        out.push('\n');
        out
    }

    /// The feature text with this block in place of an earlier one.
    ///
    /// Without an earlier block, the block goes after the last `languagesystem` statement, or
    /// at the start of the text when there is none, so its `ccmp` lookups come before the
    /// `locl` lookups of the designer in the same stage of the shaper.
    /// An empty block removes an earlier one.
    /// Err when the text has a begin line without an end line, or more than one block.
    pub fn apply_to(&self, feature_text: &str) -> Result<String, String> {
        let block = self.text();
        if let Some(range) = block_range(feature_text)? {
            let mut out = String::with_capacity(feature_text.len() + block.len());
            out.push_str(&feature_text[..range.start]);
            out.push_str(&block);
            out.push_str(&feature_text[range.end..]);
            return Ok(out);
        }
        if block.is_empty() {
            return Ok(feature_text.to_owned());
        }
        let at = after_language_systems(feature_text);
        let mut out = String::with_capacity(feature_text.len() + block.len() + 2);
        out.push_str(&feature_text[..at]);
        if at > 0 && !out.ends_with('\n') {
            out.push('\n');
        }
        if at > 0 {
            out.push('\n');
        }
        out.push_str(&block);
        let rest = &feature_text[at..];
        if !rest.is_empty() && !rest.starts_with('\n') {
            out.push('\n');
        }
        out.push_str(rest);
        Ok(out)
    }

    fn new(context: &FeatureContext) -> Self {
        Self {
            languages: context.arabic_languages(),
            ..Self::default()
        }
    }

    /// Add one feature, unless it has no rules or the feature text defines it.
    fn push(
        &mut self,
        context: &FeatureContext,
        tag: &str,
        ignore_marks: bool,
        rules: Vec<String>,
    ) {
        if rules.is_empty() {
            return;
        }
        if context.defined.contains(tag) {
            self.kept.push(tag.to_owned());
            return;
        }
        self.features.push(GeneratedFeature {
            tag: tag.to_owned(),
            ignore_marks,
            rules,
        });
    }
}

/// The position of a feature tag in the block.
fn feature_rank(tag: &str) -> usize {
    FEATURE_ORDER
        .iter()
        .position(|known| *known == tag)
        .unwrap_or(FEATURE_ORDER.len())
}

/// Write the positional and ligature features of the Arabic glyphs in `names`.
///
/// `existing_fea` is the feature text the block will go into.
/// It decides the language systems of the lookups and which features are kept.
/// Content of an earlier generated block in it is ignored.
/// Glyph names that are not Arabic give no rules: a name is Arabic when it ends in `-ar`
/// before its other suffixes, or when it is a `uniXXXX` or `uXXXXX` name in the Arabic script.
pub fn joining_features<'a>(
    names: impl IntoIterator<Item = &'a str>,
    existing_fea: &str,
) -> GeneratedBlock {
    let names: BTreeSet<&str> = names.into_iter().collect();
    let exists = |name: &str| names.contains(name);
    let context = FeatureContext::read(existing_fea);
    let mut block = GeneratedBlock::new(&context);

    for (tag, suffix) in FORMS {
        let rules = names
            .iter()
            .filter(|name| is_joining_letter(name))
            .filter_map(|name| {
                let form = format!("{name}{suffix}");
                exists(&form).then(|| format!("sub {name} by {form};"))
            })
            .collect();
        block.push(&context, tag, false, rules);
    }

    // Input sequence to ligature; the first name in name order wins a conflict.
    let mut ligatures: BTreeMap<Vec<String>, &str> = BTreeMap::new();
    for name in &names {
        let Some(form) = ligature_form(name) else {
            continue;
        };
        let Some(components) = ligature_component_names(name, exists) else {
            if base_name(name).ends_with("-ar") {
                block.notes.push(format!(
                    "{name}: a ligature component is not in the font, so no rlig rule"
                ));
            }
            continue;
        };
        if !components.iter().all(|component| is_arabic_name(component)) {
            continue;
        }
        let input = ligature_inputs(&components, form, exists);
        match ligatures.get(&input) {
            Some(other) => block.notes.push(format!(
                "{name}: {other} has the same input {}, so no rlig rule",
                input.join(" ")
            )),
            None => {
                ligatures.insert(input, name);
            }
        }
    }
    let mut ligatures: Vec<(Vec<String>, &str)> = ligatures.into_iter().collect();
    // Longer ligatures first, so that a ligature of three letters is not hidden by one of two.
    ligatures
        .sort_by(|(a, a_name), (b, b_name)| b.len().cmp(&a.len()).then_with(|| a_name.cmp(b_name)));
    let rules = ligatures
        .iter()
        .map(|(input, name)| format!("sub {} by {name};", input.join(" ")))
        .collect();
    block.push(&context, "rlig", true, rules);
    block
}

/// The components of a ligature named in the Glyphs convention, without positional suffixes.
///
/// `lam_alef-ar` and `lam_alef-ar.fina` give `lam-ar` and `alef-ar`.
/// A component is the part between underscores with the script suffix of the name, when such
/// a glyph exists, or the part itself, as in `lam-ar_alef-ar` and `uni0644_uni0627`.
/// `None` when the name has fewer than two components or a component does not exist.
pub fn ligature_component_names(name: &str, exists: impl Fn(&str) -> bool) -> Option<Vec<String>> {
    let base = base_name(name);
    if base.is_empty() || base.starts_with('_') || !base.contains('_') {
        return None;
    }
    let (stem, script) = match base.rsplit_once('-') {
        Some((stem, script)) if !script.is_empty() && !script.contains('_') => (stem, Some(script)),
        _ => (base, None),
    };
    let parts: Vec<&str> = stem.split('_').collect();
    if parts.len() < 2 || parts.iter().any(|part| part.is_empty()) {
        return None;
    }
    parts
        .into_iter()
        .map(|part| {
            if let Some(script) = script {
                let suffixed = format!("{part}-{script}");
                if exists(&suffixed) {
                    return Some(suffixed);
                }
            }
            exists(part).then(|| part.to_owned())
        })
        .collect()
}

/// The glyphs that a ligature replaces after the positional features of the shaper: the
/// positional form of each component, or its bare name when the font lacks that form.
///
/// `lam_alef-ar` gives `lam-ar.init` and `alef-ar.fina`, and `lam_alef-ar.fina` gives
/// `lam-ar.medi` and `alef-ar.fina`.
/// `None` for a name that is not a ligature with a positional or no suffix, or whose
/// components do not exist.
pub fn ligature_input_names(name: &str, exists: impl Fn(&str) -> bool) -> Option<Vec<String>> {
    let form = ligature_form(name)?;
    let components = ligature_component_names(name, &exists)?;
    Some(ligature_inputs(&components, form, exists))
}

/// The positional form of a ligature name: `""` for none, or `init`, `medi` or `fina`.
/// `None` for a name that is not a ligature, or that has another suffix.
fn ligature_form(name: &str) -> Option<&str> {
    let base = base_name(name);
    if base.starts_with('_') || !base.contains('_') {
        return None;
    }
    match name.strip_prefix(base)? {
        "" => Some(""),
        ".init" => Some("init"),
        ".medi" => Some("medi"),
        ".fina" => Some("fina"),
        _ => None,
    }
}

fn ligature_inputs(
    components: &[String],
    form: &str,
    exists: impl Fn(&str) -> bool,
) -> Vec<String> {
    let last = components.len().saturating_sub(1);
    components
        .iter()
        .enumerate()
        .map(|(index, component)| {
            // Whether the component joins the letter before it and the letter after it.
            let joins_before = index > 0 || matches!(form, "medi" | "fina");
            let joins_after = index < last || matches!(form, "init" | "medi");
            let suffix = match (joins_before, joins_after) {
                (false, true) => "init",
                (true, true) => "medi",
                (true, false) => "fina",
                (false, false) => return component.clone(),
            };
            let positional = format!("{component}.{suffix}");
            if exists(&positional) {
                positional
            } else {
                component.clone()
            }
        })
        .collect()
}

/// The name without its suffixes: the part before the first full stop.
fn base_name(name: &str) -> &str {
    name.split('.').next().unwrap_or(name)
}

/// Whether a glyph name is the isolated form of an Arabic letter: an Arabic name with no
/// suffix and no ligature underscore.
fn is_joining_letter(name: &str) -> bool {
    !name.contains('.') && !name.contains('_') && is_arabic_name(name)
}

/// Whether a glyph name is in the Arabic script by its name alone.
fn is_arabic_name(name: &str) -> bool {
    let base = base_name(name);
    if base.ends_with("-ar") {
        return true;
    }
    let hex = base
        .strip_prefix("uni")
        .filter(|hex| hex.len() == 4)
        .or_else(|| {
            base.strip_prefix('u')
                .filter(|hex| (4..=6).contains(&hex.len()))
        });
    hex.and_then(|hex| u32::from_str_radix(hex, 16).ok())
        .is_some_and(is_arabic_codepoint)
}

/// What the feature text outside the generated block declares.
#[derive(Debug, Default)]
struct FeatureContext {
    /// Feature tags with a `feature tag { ... }` definition.
    defined: BTreeSet<String>,
    /// `languagesystem` statements: script and language tags.
    language_systems: Vec<(String, String)>,
}

impl FeatureContext {
    fn read(feature_text: &str) -> Self {
        let outside = match block_range(feature_text) {
            Ok(Some(range)) => {
                format!(
                    "{}{}",
                    &feature_text[..range.start],
                    &feature_text[range.end..]
                )
            }
            _ => feature_text.to_owned(),
        };
        let tokens = tokens(&outside);
        let mut context = Self::default();
        for (index, token) in tokens.iter().enumerate() {
            let next = |offset: usize| tokens.get(index + offset).map(String::as_str);
            match token.as_str() {
                "feature" => {
                    let Some(tag) = next(1) else {
                        continue;
                    };
                    let opens = next(2) == Some("{")
                        || (next(2) == Some("useExtension") && next(3) == Some("{"));
                    if opens {
                        context.defined.insert(tag.to_owned());
                    }
                }
                "languagesystem" => {
                    if let (Some(script), Some(language), Some(";")) = (next(1), next(2), next(3)) {
                        context
                            .language_systems
                            .push((script.to_owned(), language.to_owned()));
                    }
                }
                _ => {}
            }
        }
        context
    }

    /// The languages of `script arab` other than `dflt`, or `None` without `script arab`.
    fn arabic_languages(&self) -> Option<Vec<String>> {
        let mut languages = Vec::new();
        let mut arabic = false;
        for (script, language) in &self.language_systems {
            if script == "arab" {
                arabic = true;
                if language != "dflt" && !languages.contains(language) {
                    languages.push(language.clone());
                }
            }
        }
        arabic.then_some(languages)
    }
}

/// The tokens of feature text without comments, with braces and semicolons as tokens.
fn tokens(feature_text: &str) -> Vec<String> {
    let mut out = Vec::new();
    for line in feature_text.lines() {
        let code = without_comment(line);
        let spaced = code
            .replace('{', " { ")
            .replace('}', " } ")
            .replace(';', " ; ");
        out.extend(spaced.split_whitespace().map(str::to_owned));
    }
    out
}

/// A line without its comment: the text before the first `#` that is not in a string.
fn without_comment(line: &str) -> &str {
    let mut quoted = false;
    for (at, character) in line.char_indices() {
        match character {
            '"' => quoted = !quoted,
            '#' if !quoted => return &line[..at],
            _ => {}
        }
    }
    line
}

/// The byte range of the generated block, from the start of its begin line to the end of its
/// end line, including the line break.
fn block_range(feature_text: &str) -> Result<Option<std::ops::Range<usize>>, String> {
    let mut start = None;
    let mut found = None;
    let mut offset = 0;
    for line in feature_text.split_inclusive('\n') {
        let trimmed = line.trim();
        if trimmed.starts_with(BEGIN_PREFIX) {
            if start.is_some() || found.is_some() {
                return Err("the feature text has more than one generated Arabic block".into());
            }
            start = Some(offset);
        } else if trimmed == BLOCK_END {
            let Some(begin) = start.take() else {
                return Err("the feature text ends a generated Arabic block it never began".into());
            };
            found = Some(begin..offset + line.len());
        }
        offset += line.len();
    }
    if start.is_some() {
        return Err("the generated Arabic block in the feature text has no end line".into());
    }
    Ok(found)
}

/// The byte offset after the line of the last `languagesystem` statement, or 0.
fn after_language_systems(feature_text: &str) -> usize {
    let mut offset = 0;
    let mut after = 0;
    for line in feature_text.split_inclusive('\n') {
        offset += line.len();
        if without_comment(line)
            .trim_start()
            .starts_with("languagesystem")
        {
            after = offset;
        }
    }
    after
}

/// The names of the glyphs of one source that the export writes.
pub fn exported_glyph_names(project: &Project, source: SourceId) -> Vec<&str> {
    project
        .glyph_names()
        .filter(|name| {
            project
                .document_source_glyph_metadata(source, name)
                .is_none_or(|metadata| metadata.exported())
        })
        .collect()
}

/// The skeleton table, `assets/data/arabic-skeletons.toml`.
pub const SKELETON_TABLE: &str = include_str!("../../assets/data/arabic-skeletons.toml");

/// One Arabic letter as a skeleton and marks, from the skeleton table.
#[derive(Debug, Clone, PartialEq, Eq, Deserialize)]
pub struct SkeletonLetter {
    /// The code point of the letter.
    pub codepoint: u32,
    /// The glyph name of the letter in the Glyphs convention.
    pub name: String,
    /// The glyph name of the skeleton: the body of the letter without dots.
    pub skeleton: String,
    /// The glyph names of the dot and hamza marks, in the order of the rule.
    pub marks: Vec<String>,
}

#[derive(Deserialize)]
struct SkeletonTable {
    letter: Vec<SkeletonLetter>,
}

/// The letters of the skeleton table, in the order of the file.
pub fn skeleton_letters() -> &'static [SkeletonLetter] {
    static LETTERS: OnceLock<Vec<SkeletonLetter>> = OnceLock::new();
    LETTERS.get_or_init(|| {
        toml::from_str::<SkeletonTable>(SKELETON_TABLE)
            .expect("the skeleton table is valid; a unit test parses it")
            .letter
    })
}

/// One glyph as [`ccmp_decomposition`] reads it.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct DecompositionGlyph {
    /// The glyph name.
    pub name: String,
    /// The code points that map to the glyph.
    pub codepoints: Vec<u32>,
    /// True when the glyph has no contours and no components.
    pub empty: bool,
    /// The `com.runebender.compose` recipe of the glyph, such as `"behDotless-ar + dotbelow-ar"`.
    pub recipe: Option<String>,
}

/// Write `ccmp` multiple substitutions for the empty letters of a font that has their parts.
///
/// A glyph gets a rule when it is empty, has an Arabic code point, and its parts are glyphs
/// of the font.
/// The parts are those of its `com.runebender.compose` recipe when it has one, and otherwise
/// the skeleton and marks of its code point in `letters`.
/// A letter whose positional form exists while the same form of the skeleton does not gets no
/// rule and a note, because after `ccmp` the shaper looks for the form of the skeleton.
/// A letter of `letters` whose parts exist but that no glyph encodes gets a note: the shaper
/// needs an encoded glyph to decompose.
/// `existing_fea` decides the language systems and whether `ccmp` is kept, as in
/// [`joining_features`].
pub fn ccmp_decomposition(
    glyphs: &[DecompositionGlyph],
    letters: &[SkeletonLetter],
    existing_fea: &str,
) -> GeneratedBlock {
    let context = FeatureContext::read(existing_fea);
    let mut block = GeneratedBlock::new(&context);
    let names: BTreeSet<&str> = glyphs.iter().map(|glyph| glyph.name.as_str()).collect();
    let exists = |name: &str| names.contains(name);
    let by_codepoint: HashMap<u32, &SkeletonLetter> = letters
        .iter()
        .map(|letter| (letter.codepoint, letter))
        .collect();
    let mut encoded: BTreeSet<u32> = BTreeSet::new();
    let mut rules: BTreeMap<&str, String> = BTreeMap::new();
    for glyph in glyphs {
        encoded.extend(glyph.codepoints.iter().copied());
        if !glyph.empty || !glyph.codepoints.iter().copied().any(is_arabic_codepoint) {
            continue;
        }
        let parts = match &glyph.recipe {
            Some(recipe) => {
                let parts = recipe_parts(recipe);
                if parts.len() < 2 || !parts.iter().all(|part| exists(part)) {
                    block.notes.push(format!(
                        "{}: the compose recipe \"{recipe}\" names a glyph that is not in the \
                         font, so no ccmp rule",
                        glyph.name
                    ));
                    continue;
                }
                parts
            }
            None => {
                let Some(letter) = glyph
                    .codepoints
                    .iter()
                    .find_map(|codepoint| by_codepoint.get(codepoint))
                else {
                    continue;
                };
                let parts: Vec<String> = std::iter::once(&letter.skeleton)
                    .chain(&letter.marks)
                    .cloned()
                    .collect();
                let missing: Vec<&str> = parts
                    .iter()
                    .map(String::as_str)
                    .filter(|part| !exists(part))
                    .collect();
                if !missing.is_empty() {
                    block.notes.push(format!(
                        "{}: empty, and {} not in the font, so no ccmp rule",
                        glyph.name,
                        missing.join(" and ")
                    ));
                    continue;
                }
                parts
            }
        };
        let skeleton = &parts[0];
        let lost: Vec<&str> = FORMS
            .iter()
            .map(|(_, suffix)| *suffix)
            .filter(|suffix| {
                exists(&format!("{}{suffix}", glyph.name))
                    && !exists(&format!("{skeleton}{suffix}"))
            })
            .collect();
        if !lost.is_empty() {
            block.notes.push(format!(
                "{}: the font has {} forms of it but not of {skeleton}, so no ccmp rule",
                glyph.name,
                lost.join(" ")
            ));
            continue;
        }
        rules.insert(
            glyph.name.as_str(),
            format!("sub {} by {};", glyph.name, parts.join(" ")),
        );
    }
    for letter in letters {
        let parts_exist = exists(&letter.skeleton) && letter.marks.iter().all(|mark| exists(mark));
        if parts_exist && !encoded.contains(&letter.codepoint) {
            block.notes.push(format!(
                "U+{:04X} {}: no glyph has this code point; an empty glyph with it would be \
                 composed from {} and {}",
                letter.codepoint,
                letter.name,
                letter.skeleton,
                letter.marks.join(" and ")
            ));
        }
    }
    block.push(&context, "ccmp", false, rules.into_values().collect());
    block
}

/// Whether a code point is in the Arabic script.
fn is_arabic_codepoint(codepoint: u32) -> bool {
    ARABIC_RANGES
        .iter()
        .any(|(first, last)| (*first..=*last).contains(&codepoint))
}

/// The glyphs of one source as [`ccmp_decomposition`] reads them, for the glyphs the export
/// writes.
pub fn decomposition_glyphs(project: &Project, source: SourceId) -> Vec<DecompositionGlyph> {
    let Some(layer) = project
        .document_source(source)
        .map(|source| source.default_layer())
    else {
        return Vec::new();
    };
    exported_glyph_names(project, source)
        .into_iter()
        .filter_map(|name| {
            let view = project.document_layer(name, &layer)?;
            Some(DecompositionGlyph {
                name: name.to_owned(),
                codepoints: view.codepoints().map(u32::from).collect(),
                empty: view.contours().next().is_none() && view.components().next().is_none(),
                // A recipe that is not a string is not a recipe; compose reports it.
                recipe: view
                    .composition_recipe_source()
                    .ok()
                    .flatten()
                    .map(str::to_owned),
            })
        })
        .collect()
}

/// The Arabic features of one source, generated for `feature_text`: the joining features of
/// [`joining_features`] and the decompositions of [`ccmp_decomposition`].
///
/// Glyphs that the export leaves out give no rules, since the compiled font has no such glyph.
pub fn generate_project(project: &Project, source: SourceId, feature_text: &str) -> GeneratedBlock {
    let mut block = joining_features(exported_glyph_names(project, source), feature_text);
    block.merge(ccmp_decomposition(
        &decomposition_glyphs(project, source),
        skeleton_letters(),
        feature_text,
    ));
    block
}

