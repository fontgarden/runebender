//! Arabic substitution features written from glyph names.
//!
//! A font that names its glyphs in the Glyphs convention has said most of what its Arabic
//! substitution features need.
//! `beh-ar.init`, `beh-ar.medi` and `beh-ar.fina` are the positional forms of `beh-ar`, and the
//! bare name is the isolated form.
//! `lam_alef-ar` is a ligature of `lam-ar` and `alef-ar`: underscores join the components, and
//! the script suffix `-ar` comes after the last component and before any other suffix, as in
//! `lam_alef-ar.fina`.
//! [`joining_features`] writes `isol`, `fina`, `medi` and `init` single substitutions from these
//! names, and `rlig` ligature substitutions with `lookupflag IgnoreMarks`.
//!
//! The Arabic shaper of `HarfBuzz` and `harfrust` applies `ccmp` and `locl`, then `isol`, `fina`,
//! `fin2`, `fin3`, `medi`, `med2` and `init`, each in its own stage, and then `rlig` in a later
//! stage.
//! The input of a ligature is therefore the positional forms of its components: the first
//! component of `lam_alef-ar` is `lam-ar.init` and the last is `alef-ar.fina`.
//! In a `.fina` ligature the first component joins on both sides, so `lam_alef-ar.fina` takes
//! `lam-ar.medi`.
//! A component without the form keeps its bare name, as the generated positional lookups leave
//! it.
//!
//! The output is one block of feature code between [`BLOCK_BEGIN`] and [`BLOCK_END`], placed
//! in the feature text itself, because the live layout tables do not read include files.
//! [`GeneratedBlock::apply_to`] replaces an earlier block in place, so a second run gives the
//! same text.
//! A feature that the feature text defines outside the block is never written: the
//! designer's feature stays as it is, and [`GeneratedBlock::kept`] names it.
//! The lookups are registered under `script arab` with every Arabic language system that the
//! feature text declares, or under all its language systems when it declares none for Arabic.
//!
//! [`ccmp_decomposition`] writes `ccmp` multiple substitutions into the same block, for letters
//! that a font composes from a skeleton and dot or hamza marks.
//! When the glyph of a letter such as `teh-ar` is empty and the font has its skeleton
//! `behDotless-ar` and its mark `twodotshorizontalabove-ar`, `teh-ar` becomes the skeleton and
//! the mark before the positional features run, so the skeleton takes its positional form and
//! the mark attaches to it through the anchors of the font.
//! The parts come from the `com.runebender.compose` recipe of the glyph when it has one, and
//! otherwise from `assets/data/arabic-skeletons.toml`.
//! No mark class or anchor is written here: the mark features come from the anchors.
//!
//! See items 6.2 and 6.3 in `docs/ARABIC-TEXT-LAYOUT-PLAN.md`.

use std::collections::{BTreeMap, BTreeSet, HashMap};
use std::fmt::Write as _;
use std::sync::OnceLock;

